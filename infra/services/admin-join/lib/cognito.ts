/**
 * Cognito operations for self-service registration.
 *
 * Deliberately narrow: find an account by email, create one with a suppressed
 * message, set a temporary password we deliver ourselves, and add the group.
 * The public Lambda has no reason to read groups, list members, or sign anyone
 * out, so it does not get those permissions.
 */

import {
  AdminAddUserToGroupCommand,
  AdminCreateUserCommand,
  AdminSetUserPasswordCommand,
  CognitoIdentityProviderClient,
  ListUsersCommand,
} from '@aws-sdk/client-cognito-identity-provider';

const cognito = new CognitoIdentityProviderClient({});

function poolId(): string {
  const id = process.env.USER_POOL_ID;
  if (!id) throw new Error('USER_POOL_ID is not configured');
  return id;
}

interface CognitoUserShape {
  Attributes?: Array<{ Name?: string; Value?: string }>;
  Username?: string;
  UserStatus?: string;
}

function attribute(user: CognitoUserShape, name: string): string | null {
  return user.Attributes?.find((a) => a.Name === name)?.Value ?? null;
}

export interface ExistingUser {
  sub: string;
  email: string;
  status: string;
}

/** Exact, case-insensitive match — Cognito's filter is a prefix-style expression. */
export async function findUserByEmail(email: string): Promise<ExistingUser | null> {
  const safe = email.replace(/["\\]/g, '').trim();
  if (!safe) return null;

  const response = await cognito.send(
    new ListUsersCommand({
      UserPoolId: poolId(),
      Filter: `email = "${safe}"`,
      Limit: 5,
    })
  );

  const match = (response.Users ?? []).find(
    (user) => attribute(user, 'email')?.toLowerCase() === email.toLowerCase()
  );

  if (!match) return null;

  return {
    sub: attribute(match, 'sub') ?? match.Username ?? '',
    email: attribute(match, 'email') ?? email,
    status: match.UserStatus ?? 'UNKNOWN',
  };
}

/**
 * Create the account without letting Cognito email it.
 *
 * `MessageAction: SUPPRESS` plus our own Resend email means the copy, sender and
 * deliverability are ours, while Cognito still owns the password policy and the
 * forced-change challenge. The temporary password is generated by the caller and
 * exists only in this invocation and in the email.
 */
export async function createInvitedAdmin(input: {
  email: string;
  temporaryPassword: string;
  fullName?: string;
}): Promise<{ sub: string; status: string }> {
  const created = await cognito.send(
    new AdminCreateUserCommand({
      UserPoolId: poolId(),
      Username: input.email,
      UserAttributes: [
        { Name: 'email', Value: input.email },
        { Name: 'email_verified', Value: 'true' },
        ...(input.fullName ? [{ Name: 'name', Value: input.fullName }] : []),
      ],
      MessageAction: 'SUPPRESS',
    })
  );

  const sub = attribute(created.User ?? {}, 'sub') ?? created.User?.Username ?? '';
  if (!sub) {
    throw new Error('Cognito created a user without a sub');
  }

  await cognito.send(
    new AdminSetUserPasswordCommand({
      UserPoolId: poolId(),
      Username: sub,
      Password: input.temporaryPassword,
      // False = temporary: first sign-in must replace it (NEW_PASSWORD_REQUIRED).
      Permanent: false,
    })
  );

  return { sub, status: created.User?.UserStatus ?? 'FORCE_CHANGE_PASSWORD' };
}

export async function addToGroup(sub: string, group: string): Promise<void> {
  await cognito.send(
    new AdminAddUserToGroupCommand({ UserPoolId: poolId(), Username: sub, GroupName: group })
  );
}
